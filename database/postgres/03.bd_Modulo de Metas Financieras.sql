INSERT INTO estado_metas (estado) VALUES ('EN_PROGRESO') ON CONFLICT (estado) DO NOTHING;
INSERT INTO estado_metas (estado) VALUES ('COMPLETADA') ON CONFLICT (estado) DO NOTHING;
INSERT INTO estado_metas (estado) VALUES ('VENCIDA') ON CONFLICT (estado) DO NOTHING;
INSERT INTO estado_metas (estado) VALUES ('CANCELADA') ON CONFLICT (estado) DO NOTHING;

-- ----------- METAS FINANCIERAS ------------

CREATE TABLE IF NOT EXISTS metas (
    id_meta         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre_meta     VARCHAR(80) NOT NULL,
    monto_objetivo  NUMERIC(12,2) NOT NULL,
    saldo           NUMERIC(12,2) DEFAULT 0 NOT NULL,
    fecha_limite    DATE NOT NULL,
    cod_cliente     BIGINT NOT NULL,
    id_tipo         BIGINT NOT NULL,
    id_estado       BIGINT NOT NULL,
    CONSTRAINT pk_metas PRIMARY KEY (id_meta),
    CONSTRAINT fk_metas_cliente FOREIGN KEY (cod_cliente)
        REFERENCES cliente (cod_cliente),
    CONSTRAINT fk_metas_tipo FOREIGN KEY (id_tipo)
        REFERENCES tipo_metas (id_tipo),
    CONSTRAINT fk_metas_estado FOREIGN KEY (id_estado)
        REFERENCES estado_metas (id_estado),
    CONSTRAINT ck_metas_monto_objetivo CHECK (monto_objetivo > 0),
    CONSTRAINT ck_metas_saldo_rango CHECK (saldo >= 0 AND saldo <= monto_objetivo)
);

CREATE INDEX IF NOT EXISTS ix_metas_tipo    ON metas (id_tipo);
CREATE INDEX IF NOT EXISTS ix_metas_estado  ON metas (id_estado);
CREATE INDEX IF NOT EXISTS ix_metas_cliente ON metas (cod_cliente);

-- Trigger de validacion de fecha limite
CREATE OR REPLACE FUNCTION fn_trg_valida_fecha_meta()
RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'INSERT'
       OR OLD.fecha_limite IS NULL
       OR NEW.fecha_limite <> OLD.fecha_limite THEN
        IF NEW.fecha_limite <= CURRENT_DATE THEN
            RAISE EXCEPTION 'La fecha límite de la meta debe ser mayor al día de hoy.' USING ERRCODE = 'P0001';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_valida_fecha_meta ON metas;
CREATE TRIGGER trg_valida_fecha_meta
BEFORE INSERT OR UPDATE ON metas
FOR EACH ROW
EXECUTE FUNCTION fn_trg_valida_fecha_meta();

-- --------------- APORTES -------------------

CREATE TABLE IF NOT EXISTS aportes_meta (
    id_aporte       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    monto           NUMERIC(12,2) NOT NULL,
    fecha           DATE DEFAULT CURRENT_DATE NOT NULL,
    id_meta         BIGINT NOT NULL,
    id_cuenta       BIGINT NOT NULL,
    tipo            CHAR(1) DEFAULT 'A' NOT NULL,
    CONSTRAINT pk_aportes_meta PRIMARY KEY (id_aporte),
    CONSTRAINT fk_aportes_meta_meta FOREIGN KEY (id_meta)
        REFERENCES metas (id_meta),
    CONSTRAINT fk_aportes_meta_cuenta FOREIGN KEY (id_cuenta)
        REFERENCES cuentas (id_cuenta),
    CONSTRAINT ck_aportes_meta_monto CHECK (monto > 0),
    CONSTRAINT ck_aportes_tipo CHECK (tipo IN ('A', 'R'))
);

CREATE INDEX IF NOT EXISTS ix_aportes_meta_meta   ON aportes_meta (id_meta);
CREATE INDEX IF NOT EXISTS ix_aportes_meta_cuenta ON aportes_meta (id_cuenta);

-- Validaciones de aportes
CREATE OR REPLACE FUNCTION fn_trg_valida_fecha_aportes_meta()
RETURNS trigger AS $$
DECLARE
    vf_limite DATE;
BEGIN
    IF NEW.tipo = 'A' THEN
        SELECT fecha_limite INTO vf_limite
        FROM metas WHERE id_meta = NEW.id_meta;

        IF vf_limite IS NOT NULL AND NEW.fecha > vf_limite THEN
            RAISE EXCEPTION 'No se pueden registrar aportes después de la fecha límite.' USING ERRCODE = 'P0001';
        END IF;
    END IF;
    RETURN NEW;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_valida_fecha_aportes_meta ON aportes_meta;
CREATE TRIGGER trg_valida_fecha_aportes_meta
BEFORE INSERT OR UPDATE ON aportes_meta
FOR EACH ROW
EXECUTE FUNCTION fn_trg_valida_fecha_aportes_meta();

-- Actualizacion de saldo de meta al registrar aportes o retiros
CREATE OR REPLACE FUNCTION fn_trg_actualiza_saldo_meta()
RETURNS trigger AS $$
DECLARE
    vid_meta  BIGINT;
    vdelta    NUMERIC(12,2) := 0;
    vobjetivo NUMERIC(12,2);
    vsaldo    NUMERIC(12,2);
BEGIN
    IF TG_OP = 'INSERT' THEN
        vid_meta := NEW.id_meta;
        vdelta   := CASE NEW.tipo WHEN 'A' THEN NEW.monto ELSE -NEW.monto END;
    ELSIF TG_OP = 'UPDATE' THEN
        vid_meta := NEW.id_meta;
        vdelta   := (CASE NEW.tipo WHEN 'A' THEN NEW.monto ELSE -NEW.monto END)
                   - (CASE OLD.tipo WHEN 'A' THEN OLD.monto ELSE -OLD.monto END);
    ELSE
        vid_meta := OLD.id_meta;
        vdelta   := -(CASE OLD.tipo WHEN 'A' THEN OLD.monto ELSE -OLD.monto END);
    END IF;

    SELECT monto_objetivo, saldo INTO vobjetivo, vsaldo
    FROM metas WHERE id_meta = vid_meta FOR UPDATE;

    IF (vsaldo + vdelta) > vobjetivo THEN
        RAISE EXCEPTION 'El aporte excede el monto objetivo restante.' USING ERRCODE = 'P0001';
    END IF;

    UPDATE metas
    SET saldo = saldo + vdelta,
        id_estado = CASE
                      WHEN id_estado IN (1, 2) THEN
                          CASE WHEN (saldo + vdelta) >= monto_objetivo THEN 2 ELSE 1 END
                      ELSE id_estado
                    END
    WHERE id_meta = vid_meta;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    ELSE
        RETURN NEW;
    END IF;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_actualiza_saldo_meta ON aportes_meta;
CREATE TRIGGER trg_actualiza_saldo_meta
AFTER INSERT OR UPDATE OR DELETE ON aportes_meta
FOR EACH ROW
EXECUTE FUNCTION fn_trg_actualiza_saldo_meta();

-- Procedimiento para vencer metas con fecha límite cumplida
CREATE OR REPLACE PROCEDURE sp_vencer_metas()
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE metas
    SET id_estado = 3
    WHERE id_estado = 1
      AND fecha_limite < CURRENT_DATE;
END;
$$;
