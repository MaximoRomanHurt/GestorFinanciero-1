-- ---------- CATEGORÍAS ----------

CREATE TABLE IF NOT EXISTS tipo_metas (
    id_tipo     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tipo        VARCHAR(50) NOT NULL,
    CONSTRAINT pk_tipo_metas PRIMARY KEY (id_tipo),
    CONSTRAINT uq_tipo_metas UNIQUE (tipo)
);

CREATE TABLE IF NOT EXISTS estado_metas (
    id_estado   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    estado      VARCHAR(50) NOT NULL,
    CONSTRAINT pk_estado_metas PRIMARY KEY (id_estado),
    CONSTRAINT uq_estado_metas UNIQUE (estado)
);

