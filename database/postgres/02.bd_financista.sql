-- ---------- CATEGORÍAS ----------

CREATE TABLE IF NOT EXISTS categoria_cuentas (
    id_categoria  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    categoria     VARCHAR(50) NOT NULL,
    CONSTRAINT pk_categoria_cuentas PRIMARY KEY (id_categoria),
    CONSTRAINT uq_categoria_cuentas UNIQUE (categoria)
);

CREATE TABLE IF NOT EXISTS categoria_gastos (
    id_categoria  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    categoria     VARCHAR(50) NOT NULL,
    CONSTRAINT pk_categoria_gastos PRIMARY KEY (id_categoria),
    CONSTRAINT uq_categoria_gastos UNIQUE (categoria)
);

CREATE TABLE IF NOT EXISTS categoria_ingresos (
    id_categoria  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    categoria     VARCHAR(50) NOT NULL,
    CONSTRAINT pk_categoria_ingresos PRIMARY KEY (id_categoria),
    CONSTRAINT uq_categoria_ingresos UNIQUE (categoria)
);

-- ---------- CLIENTE Y USUARIO ----------

CREATE TABLE IF NOT EXISTS cliente (
    cod_cliente  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ap_paterno   VARCHAR(50) NOT NULL,
    ap_materno   VARCHAR(50),
    nombres      VARCHAR(100) NOT NULL,
    CONSTRAINT pk_cliente PRIMARY KEY (cod_cliente)
);

CREATE TABLE IF NOT EXISTS usuario (
    id_usuario   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    usuario      VARCHAR(50) NOT NULL,
    clave        VARCHAR(100) NOT NULL,
    cod_cliente  BIGINT NOT NULL,
    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuario_usuario UNIQUE (usuario),
    CONSTRAINT uq_usuario_cliente UNIQUE (cod_cliente),
    CONSTRAINT fk_usuario_cliente FOREIGN KEY (cod_cliente)
        REFERENCES cliente (cod_cliente)
);

-- ---------- CUENTAS ----------

CREATE TABLE IF NOT EXISTS cuentas (
    id_cuenta       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre_cuenta   VARCHAR(80) NOT NULL,
    cod_cliente     BIGINT NOT NULL,
    id_categoria    BIGINT NOT NULL,
    saldo           NUMERIC(12,2) DEFAULT 0 NOT NULL,
    CONSTRAINT pk_cuentas PRIMARY KEY (id_cuenta),
    CONSTRAINT fk_cuentas_cliente FOREIGN KEY (cod_cliente)
        REFERENCES cliente (cod_cliente),
    CONSTRAINT fk_cuentas_categoria FOREIGN KEY (id_categoria)
        REFERENCES categoria_cuentas (id_categoria),
    CONSTRAINT ck_cuentas_saldo CHECK (saldo >= 0)
);

CREATE INDEX IF NOT EXISTS ix_cuentas_cliente   ON cuentas (cod_cliente);
CREATE INDEX IF NOT EXISTS ix_cuentas_categoria ON cuentas (id_categoria);

-- ---------- TRANSFERENCIAS --------

CREATE TABLE IF NOT EXISTS transferencias (
    id_transferencia    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    monto               NUMERIC(12,2) NOT NULL,
    fecha               DATE DEFAULT CURRENT_DATE NOT NULL,
    id_cuentaog         BIGINT NOT NULL,
    id_cuentades        BIGINT NOT NULL,
    CONSTRAINT pk_transferencias PRIMARY KEY (id_transferencia),
    CONSTRAINT fk_transferencias_cuentaog FOREIGN KEY (id_cuentaog)
        REFERENCES cuentas (id_cuenta),
    CONSTRAINT fk_transferencias_cuentades FOREIGN KEY (id_cuentades)
        REFERENCES cuentas (id_cuenta),
    CONSTRAINT ck_transferencias_monto CHECK (monto > 0)
);

CREATE INDEX IF NOT EXISTS ix_transferencias_cuentaog  ON transferencias (id_cuentaog);
CREATE INDEX IF NOT EXISTS ix_transferencias_cuentades ON transferencias (id_cuentades);
CREATE INDEX IF NOT EXISTS ix_transferencias_fecha     ON transferencias (fecha);

-- ---------- MOVIMIENTOS ----------

CREATE TABLE IF NOT EXISTS movimientos (
    id_movimiento  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tipo           CHAR(1) NOT NULL,
    descripcion    VARCHAR(200),
    monto          NUMERIC(12,2) NOT NULL,
    fecha          DATE DEFAULT CURRENT_DATE NOT NULL,
    id_cuenta      BIGINT NOT NULL,
    CONSTRAINT pk_movimientos PRIMARY KEY (id_movimiento),
    CONSTRAINT fk_movimientos_cuenta FOREIGN KEY (id_cuenta)
        REFERENCES cuentas (id_cuenta),
    CONSTRAINT ck_movimientos_tipo  CHECK (tipo IN ('I', 'G')),
    CONSTRAINT ck_movimientos_monto CHECK (monto > 0)
);

CREATE INDEX IF NOT EXISTS ix_movimientos_cuenta ON movimientos (id_cuenta);
CREATE INDEX IF NOT EXISTS ix_movimientos_fecha  ON movimientos (fecha);

-- ---------- INGRESOS Y GASTOS (detalle del movimiento) ----------

CREATE TABLE IF NOT EXISTS ingresos (
    id_movimiento  BIGINT NOT NULL,
    id_categoria   BIGINT NOT NULL,
    CONSTRAINT pk_ingresos PRIMARY KEY (id_movimiento),
    CONSTRAINT fk_ingresos_movimiento FOREIGN KEY (id_movimiento)
        REFERENCES movimientos (id_movimiento) ON DELETE CASCADE,
    CONSTRAINT fk_ingresos_categoria FOREIGN KEY (id_categoria)
        REFERENCES categoria_ingresos (id_categoria)
);

CREATE INDEX IF NOT EXISTS ix_ingresos_categoria ON ingresos (id_categoria);

CREATE TABLE IF NOT EXISTS gastos (
    id_movimiento  BIGINT NOT NULL,
    id_categoria   BIGINT NOT NULL,
    CONSTRAINT pk_gastos PRIMARY KEY (id_movimiento),
    CONSTRAINT fk_gastos_movimiento FOREIGN KEY (id_movimiento)
        REFERENCES movimientos (id_movimiento) ON DELETE CASCADE,
    CONSTRAINT fk_gastos_categoria FOREIGN KEY (id_categoria)
        REFERENCES categoria_gastos (id_categoria)
);

CREATE INDEX IF NOT EXISTS ix_gastos_categoria ON gastos (id_categoria);

